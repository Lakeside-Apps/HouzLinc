using System.Text.RegularExpressions;
using Insteon.Model;
using Insteon.Serialization.Houselinc;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace UnitTests.Insteon;

public static class ModelHolderForTest
{
    // Input models (Models folder) and reference files (Refs folder) are copied next to the test assembly
    private static string InputFolder => AppContext.BaseDirectory;

    // Files generated by the tests go to a temp folder, so they can be inspected when a comparison fails
    private static string TestOutputFolder => Path.Combine(Path.GetTempPath(), "HouzLincTests");

    /// <summary>
    /// Load a test file from the Models folder
    /// </summary>
    /// <param name="subfolder"></param>
    /// <param name="filename"></param>
    /// <returns></returns>
    public static async Task<House?> LoadFromFile(string subfolder, string filename)
    {
        using var stream = File.OpenRead(Path.Combine(InputFolder, "Models", subfolder, filename + ".xml"));

        // Deserialize the model
        return await HLSerializer.Deserialize(stream);
    }

    /// <summary>
    /// Save test file to the test output folder
    /// </summary>
    /// <param name="filename"></param>
    /// <returns>Full path of the file</returns>
    public static async Task<string> SaveToFile(string subfolder, string filename, House house)
    {
        var testSubFolder = Path.Combine(TestOutputFolder, subfolder);
        Directory.CreateDirectory(testSubFolder);
        var path = Path.Combine(testSubFolder, filename + ".xml");
        using (var stream = File.Create(path))
        {
            Assert.IsTrue(await HLSerializer.Serialize(stream, house));
        }
        return path;
    }

    /// <summary>
    /// Compare a test file stored in the test output folder with a ref file stored in the Refs folder
    /// </summary>
    /// <param name="subfolder">subfolder under these folders where the files are</param>
    /// <param name="testFilename">name of the test file without extension</param>
    /// <returns>null if files are the same, description of first difference otherwise</returns>
    public static async Task<string?> CompareFiles(string subfolder, string testFilename)
    {
        IList<string>? refLines = null;
        IList<string>? testLines = null;

        string pathRefFile = Path.Combine(InputFolder, "Refs", subfolder, testFilename + ".xml");
        string pathTestFile = Path.Combine(TestOutputFolder, subfolder, testFilename + ".xml");

        try
        {
            refLines = await File.ReadAllLinesAsync(pathRefFile);
        }
        catch (Exception)
        {
            return $"Can't open ref file {pathRefFile}";
        }

        try
        {
            testLines = await File.ReadAllLinesAsync(pathTestFile);
        }
        catch (Exception)
        {
            return $"Can't open Test file {pathTestFile}";
        }

        string? result = null;
        int count = refLines.Count < testLines.Count ? refLines.Count : testLines.Count;
        int i = 0;
        for (; i < count; i++)
        {
            // Remove LastUpdate and notes/added attribute values as they are time stamps that change everytime 
            // Also remove uid values as they will change every run for newly created records/scene members.
            string pattern = @"(.*lastUpdate=\s*|.*notes added=\s*|.*uid=\s*)""[^""]*""(.*)";
            string replacement = "$1\"...\"$2";
            refLines[i] = Regex.Replace(refLines[i], pattern, replacement);
            testLines[i] = Regex.Replace(testLines[i], pattern, replacement);

            if (testLines[i] != refLines[i])
            {
                result = "\r\n" +
                    "Ref File:  " + pathRefFile + "\r\n" + 
                    "Test File: " + pathTestFile + "\r\n" +
                    "Differ line " + i + " \r\n" +
                    "Ref: " + refLines[i] + "\r\n" +
                    "Test:" + testLines[i];
                break;
            }
        }

        if (i == count)
        {
            if (i < refLines.Count)
            {
                result = "Ref file has more lines than test file";

            }
            else if (i < testLines.Count)
            {
                result = "Test file has more lines than ref file";
            }
        }

        return result;
    }
}
